for country in merged['Country'].unique():
    subset = merged[merged['Country'] == country]
    plt.plot(subset['Year'], subset['Inflation'], label=country)

plt.legend()
plt.xticks(rotation=90)
plt.title("Inflation Trends")
plt.xlabel('Year')
plt.ylabel('Inflation')
plt.show()


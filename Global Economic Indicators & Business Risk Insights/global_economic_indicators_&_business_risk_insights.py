#Inflation JSON Data Ingestion:

url = r"http://api.worldbank.org/v2/country/NGA;GHA;KEN/indicator/FP.CPI.TOTL.ZG?format=json&per_page=1000"
response = requests.get(url)
data = response.json()

#Inspect Data Structure
print(data)
print(type(data))
print(len(data))

#GDP JSON Data Ingestion:

url = r"http://api.worldbank.org/v2/country/NGA;GHA;KEN/indicator/NY.GDP.MKTP.KD.ZG?format=json&per_page=1000"
response = requests.get(url)
data = response.json()

#Inspect Data Structure
print(data)
print(type(data))
print(len(data))

"""####**JSON Data Structure**
The returned JSON is a list containing a dictionary and a list:
- The first element (dictionary) contains the metadata.
- The second element (list) contains the dictionary of actual record.

Metadata: current page, total number of pages, number of records per page, current number of records, sourceid, lastupdate info.
"""

#Extract Inflation Data Point and Normalize JSON
records = data[1]
df_inf = pd.json_normalize(records)

#Inspect Dataframe
print(df_inf.head())

#Select Relevant Columns and Inspect Dataframe
df_inf = df_inf[['country.value', 'date', 'value']]
df_inf.columns = ['Country', 'Year', 'Inflation']
print('\n\n',df_inf.head())

#Extract GDP Data Point and Normalize JSON
records = data[1]
df_gdp = pd.json_normalize(records)

#Inspect Dataframe
print(df_gdp.head())

#Select Relevant Columns and Inspect Dataframe
df_gdp = df_gdp[['country.value', 'date', 'value']]
df_gdp.columns = ['Country', 'Year', 'GDP']
print('\n\n',df_gdp.head())

"""####**Rationale For Feature Selection**
For clarity purposes,
- Only country.value, date and value columns were retained in the dataframes.
- The Selected features were renamed as:
  - country.value (contains full official names of countries) >> Country
  - date (contains only year) >> Year
  - value (contains actual inflation/GDP figures) >> Inflation/GDP
- Other features were dropped to facilitate easy analysis since retaining them do not contribute any significant gains in insights.
"""

#Inflation Data Validation
print(df_inf.isnull().sum())
print('\n',df_inf[df_inf.isnull().any(axis=1)])

# Check for Extreme Values
quantile_bins = [0, 0.90, 0.95, 0.98, 0.99, 1.0]
labels = ['Below 90th %ile', '90th-95th %ile', '95th-98th %ile', '99th %ile', 'Top 1%']
df_inf['Quantile_Bin'] = pd.qcut(df_inf['Inflation'], q=quantile_bins, labels=labels)

top_10_percent = df_inf[df_inf['Inflation'] >= df_inf['Inflation'].quantile(0.90)]
print('\n', top_10_percent.sort_values(by=['Country','Year'], ascending=True), '\n')

df_inf.describe()

#GDP Data Validation
print(df_gdp.isnull().sum())
print('\n',df_gdp[df_gdp.isnull().any(axis=1)])

# Check for Extreme Values
quantile_bins = [0, 0.90, 0.95, 0.98, 0.99, 1.0]
labels = ['Below 90th %ile', '90th-95th %ile', '95th-98th %ile', '99th %ile', 'Top 1%']
df_gdp['Quantile_Bin'] = pd.qcut(df_gdp['GDP'], q=quantile_bins, labels=labels)

top_10_percent = df_gdp[df_gdp['GDP'] >= df_gdp['GDP'].quantile(0.90)]
print('\n', top_10_percent.sort_values(by=['Country','Year'], ascending=True), '\n')

df_gdp.describe()

"""####**Missing Values**
- **Inflation**
  - **Missing Values**
    - Country entries: No missing values
    - Year entries: No missing values
    - inflation enteries: 5 (Ghana inflation enteries for the year 1960 - 1964)

  - **Extreme Values**

    Ghana inflation values for the years 1977, 1981 and 1983 are greater than 98th percentile of inflation enteries, and therefore are potential outliers (https://tinyurl.com/Ghana-inflation-trend).

- **GDP**
  - **Missing Values**
    - Country entries: No missing values
    - Year entries: No missing values
    - GDP enteries: 3 (Nigeria, Ghana and Kenya GDP entries for the year 1960)

  - **Extreme Values**

    Nigeria GDP values for the years 1969 and 1970 are greater than 98th percentile of GDP enteries, and therefore are potential outliers (https://tinyurl.com/Nigeria-GDP-trend)
"""

# Handle Inflation Missing Values and Outliers

#- Calculate Mean and 98th Percentile for Inflation by Country
group_mean_inf = df_inf.groupby('Country')['Inflation'].transform('mean')
group_98th_inf = df_inf.groupby('Country')['Inflation'].transform(lambda x: x.quantile(0.98))

#- Replace Missing Values and all values > 98th percentile with country's mean inflation
mask = (df_inf['Inflation'].isna()) | (df_inf['Inflation'] > group_98th_inf)
df_inf.loc[mask, 'Inflation'] = group_mean_inf

#- Inspect Cleaned Dataframe
print(df_inf)

df_inf['Quantile_Bin'] = pd.qcut(df_inf['Inflation'], q=quantile_bins, labels=labels)
top_10_percent = df_inf[df_inf['Inflation'] >= df_inf['Inflation'].quantile(0.90)]
print('\n', top_10_percent.sort_values(by=['Country','Year'], ascending=True), '\n')

df_inf.describe()

# Handle GDP Missing Values and Outliers

#- Calculate Mean and 98th Percentile for Inflation by Country
group_mean_gdp = df_gdp.groupby('Country')['GDP'].transform('mean')
group_98th_gdp = df_gdp.groupby('Country')['GDP'].transform(lambda x: x.quantile(0.98))

#- Replace Missing Values and all values > 98th percentile with country's mean inflation
mask = (df_gdp['GDP'].isna()) | (df_gdp['GDP'] > group_98th_gdp)
df_gdp.loc[mask, 'GDP'] = group_mean_gdp

#- Inspect Cleaned Dataframe
print(df_gdp.isnull().sum())
print('\n',df_gdp[df_gdp.isnull().any(axis=1)])
print(df_gdp)

df_gdp['Quantile_Bin'] = pd.qcut(df_gdp['GDP'], q=quantile_bins, labels=labels)
top_10_percent = df_gdp[df_gdp['GDP'] >= df_gdp['GDP'].quantile(0.90)]
print('\n', top_10_percent.sort_values(by=['Country','Year'], ascending=True), '\n')

df_gdp.describe()

"""####**How Missing values and Outliers were handled**

- All rows were retained in the analysis
- Missing Values and outliers were replaced with the mean inflation value for Ghana
- Missing Values and outliers were replaced with the mean GDP value for the respective country.
"""

#Merge the Dataframes
merged = pd.merge(df_inf, df_gdp, on=['Country','Year'], how='inner')
print(merged)

"""####**Why Inner Join?**
Inner join ensures a balance dataset in which there are both inflation and GDP data points for all countries in the respective years
The merged data will contain only 195 records (the total number of records in the both dataset) resulting in no loss of data.
"""

from datetime import datetime

#Exploratory Data Analysis
